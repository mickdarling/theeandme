import json
import time
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Any

class VoiceContextManager:
    """Manages infinite session memory for voice automation"""

    def __init__(self, claude_md_path: str = "/Users/mick/Developer/theeandme/CLAUDE.md"):
        self.claude_md_path = Path(claude_md_path)
        self.session_start = time.time()
        self.voice_interactions = []
        self.session_summary = {
            "start_time": datetime.now().isoformat(),
            "commands_executed": 0,
            "key_decisions": [],
            "preferences_learned": [],
            "context_evolution": []
        }

    def add_voice_interaction(self, user_voice: str, claude_response: str,
                            command_executed: bool = False, tools_used: List[str] = None):
        """Add voice interaction to session memory"""
        interaction = {
            "timestamp": datetime.now().isoformat(),
            "user_voice": user_voice,
            "claude_response": claude_response,
            "command_executed": command_executed,
            "tools_used": tools_used or [],
            "response_length": len(claude_response)
        }

        self.voice_interactions.append(interaction)
        self.session_summary["commands_executed"] += 1 if command_executed else 0

        # Extract key decisions and preferences
        self._extract_context_evolution(user_voice, claude_response)

    def _extract_context_evolution(self, user_voice: str, claude_response: str):
        """Extract key decisions and preferences from interaction"""
        user_lower = user_voice.lower()

        # Detect preference expressions
        if any(phrase in user_lower for phrase in ['i prefer', 'i like', 'i want', 'i need']):
            self.session_summary["preferences_learned"].append({
                "preference": user_voice,
                "timestamp": datetime.now().isoformat()
            })

        # Detect decision points
        if any(phrase in user_lower for phrase in ['yes', 'no', 'approve', 'allow', 'always']):
            self.session_summary["key_decisions"].append({
                "decision": user_voice,
                "context": claude_response[:100] + "...",
                "timestamp": datetime.now().isoformat()
            })

        # Track system evolution
        if 'verbose' in user_lower or 'detailed' in user_lower:
            self.session_summary["context_evolution"].append({
                "change": "User requested verbose responses",
                "timestamp": datetime.now().isoformat()
            })

    def generate_session_summary(self) -> str:
        """Generate compressed session summary for CLAUDE.md injection"""
        session_duration = time.time() - self.session_start

        # Key interaction summary
        successful_commands = [i for i in self.voice_interactions if i["command_executed"]]
        conversation_interactions = [i for i in self.voice_interactions if not i["command_executed"]]

        summary = f"""
# Voice Automation Session Summary
**Session Date**: {datetime.now().strftime("%Y-%m-%d %H:%M")}
**Duration**: {session_duration/60:.1f} minutes
**Total Interactions**: {len(self.voice_interactions)}

## Command Execution Summary
**Successful Commands**: {len(successful_commands)}
**Tools Used**: {self._get_unique_tools_used()}

## Key Voice Commands Executed
"""

        # Add top 5 successful commands
        for cmd in successful_commands[-5:]:
            summary += f"- **\"{cmd['user_voice']}\"** → {cmd['tools_used']}\n"

        summary += f"""

## User Preferences Learned
"""
        for pref in self.session_summary["preferences_learned"][-3:]:
            summary += f"- {pref['preference']}\n"

        summary += f"""

## Context for Next Session
- Voice recognition accuracy: Excellent (RealtimeSTT working well)
- Claude Code integration: {self._assess_claude_integration()}
- User verbosity preference: {self._detect_verbosity_preference()}
- Permission handling: {self._assess_permission_handling()}

## Technical Status
- Local RealtimeSTT: ✅ Working excellently
- Echo blocking: ✅ Functional
- Claude Code automation: {self._assess_automation_status()}
- Context persistence: ✅ This system now active

---
*Generated by Voice Context Manager - Autonomous Session Memory*
"""

        return summary

    def _get_unique_tools_used(self) -> str:
        """Get unique tools used across session"""
        all_tools = []
        for interaction in self.voice_interactions:
            all_tools.extend(interaction.get("tools_used", []))

        unique_tools = list(set(all_tools))
        return ", ".join(unique_tools) if unique_tools else "None detected"

    def _assess_claude_integration(self) -> str:
        """Assess Claude Code integration quality"""
        successful = len([i for i in self.voice_interactions if i["command_executed"]])
        total = len([i for i in self.voice_interactions if any(tool in i.get("tools_used", []) for tool in ["Bash", "Read", "Write"])])

        if total == 0:
            return "Limited testing"

        success_rate = successful / total * 100
        return f"{success_rate:.0f}% success rate"

    def _detect_verbosity_preference(self) -> str:
        """Detect user's verbosity preference"""
        verbose_requests = [i for i in self.voice_interactions
                          if any(word in i["user_voice"].lower() for word in ['verbose', 'detailed', 'explain', 'more'])]

        return "Detailed responses preferred" if verbose_requests else "Standard responses"

    def _assess_permission_handling(self) -> str:
        """Assess permission handling effectiveness"""
        permission_mentions = [i for i in self.voice_interactions
                             if 'permission' in i["claude_response"].lower()]

        return f"Needs improvement ({len(permission_mentions)} permission issues)" if permission_mentions else "Working well"

    def _assess_automation_status(self) -> str:
        """Assess overall automation effectiveness"""
        command_success_rate = len([i for i in self.voice_interactions if i["command_executed"]]) / max(len(self.voice_interactions), 1) * 100

        if command_success_rate > 80:
            return "✅ Highly effective"
        elif command_success_rate > 50:
            return "⚠️ Moderately effective"
        else:
            return "❌ Needs improvement"

    def update_claude_md(self):
        """Update CLAUDE.md with session context"""
        try:
            # Read existing CLAUDE.md
            if self.claude_md_path.exists():
                existing_content = self.claude_md_path.read_text()
            else:
                existing_content = "# Voice Automation Project Context\n\n"

            # Generate session summary
            session_summary = self.generate_session_summary()

            # Update CLAUDE.md with new context
            updated_content = existing_content + "\n" + session_summary

            # Keep CLAUDE.md manageable (last 3 session summaries)
            lines = updated_content.split('\n')
            if len(lines) > 200:  # Approximately 3 session summaries
                # Keep header + last 150 lines
                updated_content = '\n'.join(lines[:50] + lines[-150:])

            self.claude_md_path.write_text(updated_content)

            print(f"📝 CLAUDE.md updated with voice session context")
            print(f"📊 Session: {len(self.voice_interactions)} interactions, {self.session_summary['commands_executed']} commands")

        except Exception as e:
            print(f"⚠️ CLAUDE.md update failed: {e}")

    def get_context_for_claude(self) -> str:
        """Get compressed context for Claude Code injection"""
        if not self.voice_interactions:
            return ""

        # Last 3 interactions for immediate context
        recent_context = []
        for interaction in self.voice_interactions[-3:]:
            recent_context.append(f"User: {interaction['user_voice']}")
            # Compress Claude response to key points
            response_summary = interaction['claude_response'][:100] + "..." if len(interaction['claude_response']) > 100 else interaction['claude_response']
            recent_context.append(f"Assistant: {response_summary}")

        context_summary = f"""
Voice Session Context:
{chr(10).join(recent_context)}

User Preferences: {self._detect_verbosity_preference()}
Session Commands: {self.session_summary['commands_executed']} executed
"""

        return context_summary


